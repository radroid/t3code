#!/usr/bin/env node
/**
 * Builds report.html from report.src.html by inlining each prototype into an
 * <iframe srcdoc>.
 *
 * Why srcdoc rather than src: the report has to open from a plain file:// path
 * with no server. A same-directory iframe src works in some browsers and is
 * blocked in others; srcdoc always renders.
 *
 * How self-contained: the embedded prototypes are — srcdoc plus the inlined
 * _shell.css, no network and no file access. The report chrome is not: it still
 * fetches Google Fonts (with local fallbacks, so it degrades to system fonts
 * offline), and the "Open standalone" links assume the sibling prototypes/ dir.
 *
 * Marker format:
 *   <!--EMBED:file.html|height|tag|name|hint-->
 *
 * Run: two steps, both required —
 *   node docs/coil/loops-v2/build-report.mjs
 *   vp fmt docs/coil/loops-v2/report.html
 *
 * The committed report.html is formatted output. Building alone emits the same
 * page with different whitespace, so committing it lands a ~15k-line diff that
 * changes nothing. Build then format and the file reproduces byte for byte.
 */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const here = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const protoDir = NodePath.join(here, "prototypes");

const shellCss = NodeFS.readFileSync(NodePath.join(protoDir, "_shell.css"), "utf8");

/** Inline the shared stylesheet so the iframe needs no network or file access. */
function inlineCss(html) {
  const linkRe = /<link rel="stylesheet" href="_shell\.css"\s*\/?>/;
  if (!linkRe.test(html)) {
    throw new Error("prototype is missing the _shell.css link — refusing to emit a broken frame");
  }
  return html.replace(linkRe, () => `<style>\n${shellCss}\n</style>`);
}

/**
 * Escape for HTML text or a double-quoted attribute. Order matters: & first, or
 * the entities produced below get double-escaped.
 */
function escapeHtml(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

const src = NodeFS.readFileSync(NodePath.join(here, "report.src.html"), "utf8");

let embedded = 0;
const out = src.replace(
  /<!--EMBED:([^|]+)\|(\d+)\|([^|]*)\|([^|]*)\|([^>]*?)-->/g,
  (_m, file, height, tag, name, hint) => {
    const raw = NodeFS.readFileSync(NodePath.join(protoDir, file.trim()), "utf8");
    const doc = escapeHtml(inlineCss(raw));
    embedded += 1;
    return `<div class="proto">
        <div class="proto-bar">
          <span class="proto-tag">${escapeHtml(tag)}</span>
          <span class="proto-name">${escapeHtml(name)}</span>
          <span class="proto-hint">${escapeHtml(hint)}</span>
          <a class="proto-open" href="prototypes/${escapeHtml(file.trim())}" target="_blank" rel="noopener">Open standalone ↗</a>
        </div>
        <iframe title="${escapeHtml(name)}" height="${height}" loading="lazy" srcdoc="${doc}"></iframe>
      </div>`;
  },
);

/**
 * Assert the COUNT, not merely "at least one".
 *
 * The old guard only fired when *zero* markers matched, so a single drifted marker — the hint
 * regex terminates on `>` and splits on `|`, both of which are easy to type into a caption —
 * silently emitted a report missing that frame. Invisible in the browser and invisible in a
 * 15k-line diff. Reproduced with 7 of 8 inlined and no error (issue #125 §C11).
 *
 * Two directions, because they catch different mistakes: a marker that stopped matching, and a
 * prototype nobody referenced.
 */
const prototypeFiles = NodeFS.readdirSync(protoDir)
  .filter((name) => name.endsWith(".html") && !name.startsWith("_"))
  .sort();

if (embedded !== prototypeFiles.length) {
  throw new Error(
    `inlined ${embedded} prototypes but prototypes/ holds ${prototypeFiles.length} ` +
      `(${prototypeFiles.join(", ")}) — a marker has drifted, or a prototype was added without one`,
  );
}

const unreferenced = prototypeFiles.filter((name) => !src.includes(`<!--EMBED:${name}|`));
if (unreferenced.length > 0) {
  throw new Error(`prototypes never referenced by report.src.html: ${unreferenced.join(", ")}`);
}

const doctype = "<!doctype html>";
if (!out.startsWith(doctype)) throw new Error("report.src.html no longer starts with a doctype");

/** So nobody hand-edits the generated file, and nobody stops after step one. */
const marked = `${doctype}\n<!-- GENERATED by build-report.mjs from report.src.html + prototypes/* — edit those, then re-run both steps: node docs/coil/loops-v2/build-report.mjs && vp fmt docs/coil/loops-v2/report.html -->${out.slice(doctype.length)}`;

NodeFS.writeFileSync(NodePath.join(here, "report.html"), marked);

const kb = (Buffer.byteLength(marked) / 1024).toFixed(0);
console.log(`report.html written — ${embedded} prototypes inlined, ${kb} KB`);
console.log("now run: vp fmt docs/coil/loops-v2/report.html");
